"""Generate tools/ee_change_series.js, an Earth Engine Code Editor script with the 27 sampled points written in.

    python tools/make_change_series_script.py
Then paste tools/ee_change_series.js into https://code.earthengine.google.com, press Run, and run the two export tasks:
    terrapulse_change_series  -> save as backend/data/change_series.csv   (NDVI/NBR/rain/Hansen for the same Jan-Mar window each year)
    terrapulse_hansen_loss    -> save as backend/data/hansen_loss.csv     (every Hansen loss pixel in the study box)
Fire (FIRMS) is cross-checked by the backend from backend/data/fire_detections.csv, so it is not exported here.
"""
import json, pathlib
from _points import bbox, points

JS = r"""/**
 * TerraPulse - Change Over Time export  (generated by tools/make_change_series_script.py; do not edit the POINTS list by hand)
 * Same seasonal window every year, Landsat 8/9 Collection 2 Level-2, so a season is never mistaken for a change.
 * Exports: terrapulse_change_series (point x year) and terrapulse_hansen_loss (Hansen loss pixels in the study box).
 */
var POINTS = __POINTS__;
var BOX = ee.Geometry.Rectangle(__BOX__);
var YEARS = ee.List.sequence(2014, 2024).getInfo();   // Landsat 8 starts 2013; 2014 is the first full January-March window
var START_MONTH = 1, END_MONTH = 3;                    // Jan-Mar: the lowest-rainfall window in this area; change here if you wish
var WINDOW = ('0' + START_MONTH).slice(-2) + '-' + ('0' + END_MONTH).slice(-2);

function maskSR(img) {
  var qa = img.select('QA_PIXEL');
  var clear = qa.bitwiseAnd(1 << 1).eq(0).and(qa.bitwiseAnd(1 << 3).eq(0)).and(qa.bitwiseAnd(1 << 4).eq(0)).and(qa.bitwiseAnd(1 << 5).eq(0)); // dilated cloud, cloud, shadow, snow
  var sr = img.select('SR_B.').multiply(0.0000275).add(-0.2);
  return sr.updateMask(clear).copyProperties(img, ['system:time_start']);
}
var L = ee.ImageCollection('LANDSAT/LC08/C02/T1_L2').merge(ee.ImageCollection('LANDSAT/LC09/C02/T1_L2')).filterBounds(BOX);
var hansen = ee.Image('UMD/hansen/global_forest_change_2023_v1_1');
var loss = hansen.select('lossyear').unmask(0).rename('hansen_loss_year');   // no loss is a masked pixel: unmask(0)
var chirps = ee.ImageCollection('UCSB-CHG/CHIRPS/DAILY');

var pts = ee.FeatureCollection(POINTS.map(function (p) {
  return ee.Feature(ee.Geometry.Point([p.lon, p.lat]), {point_id: p.id, latitude: p.lat, longitude: p.lon});
}));

var rows = ee.FeatureCollection(YEARS.map(function (y) {
  var a = ee.Date.fromYMD(y, START_MONTH, 1), b = ee.Date.fromYMD(y, END_MONTH, 1).advance(1, 'month');
  var comp = L.filterDate(a, b).map(maskSR).median();
  var idx = comp.normalizedDifference(['SR_B5', 'SR_B4']).rename('ndvi')
      .addBands(comp.normalizedDifference(['SR_B5', 'SR_B7']).rename('nbr'));
  var rain = chirps.filterDate(a, b).sum().rename('rain_mm');
  var img = idx.addBands(rain).addBands(loss);
  return img.reduceRegions({collection: pts, reducer: ee.Reducer.mean(), scale: 30, tileScale: 4}).map(function (f) {
    return f.set({year: y, window: WINDOW});
  });
})).flatten();

// keep rows where Landsat had at least one clear view (a null NDVI means no usable image: it is dropped, never filled in)
rows = rows.filter(ee.Filter.notNull(['ndvi', 'nbr']));
Export.table.toDrive({collection: rows, description: 'terrapulse_change_series', fileFormat: 'CSV',
  selectors: ['point_id', 'latitude', 'longitude', 'year', 'window', 'ndvi', 'nbr', 'rain_mm', 'hansen_loss_year']});

var lossPix = ee.Image.pixelLonLat().addBands(hansen.select('lossyear'))
  .updateMask(hansen.select('lossyear').gt(0)).sample({region: BOX, scale: 30, geometries: false, tileScale: 4});
Export.table.toDrive({collection: lossPix, description: 'terrapulse_hansen_loss', fileFormat: 'CSV', selectors: ['latitude', 'longitude', 'lossyear']});

Map.centerObject(BOX, 10);
Map.addLayer(pts, {color: 'yellow'}, 'sampled points');
print('Points:', pts.size(), '| window', WINDOW, '| years', YEARS);
"""

pts = [{"id": p["id"], "lat": round(p["lat"], 6), "lon": round(p["lon"], 6)} for p in points()]
w, s, e, n = bbox()
out = JS.replace("__POINTS__", json.dumps(pts)).replace("__BOX__", json.dumps([round(w, 4), round(s, 4), round(e, 4), round(n, 4)]))
dest = pathlib.Path(__file__).resolve().parent / "ee_change_series.js"
dest.write_text(out, encoding="utf-8")
print(f"Wrote {dest} with {len(pts)} points. Paste it into the Earth Engine Code Editor and run the two export tasks.")

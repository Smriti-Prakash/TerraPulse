"""Generate tools/ee_monthly_series.js, an Earth Engine Code Editor script that exports MONTHLY NDVI, NBR and rainfall at the 27 sampled points.

    python tools/make_monthly_series_script.py
Then paste tools/ee_monthly_series.js into https://code.earthengine.google.com, press Run, start the export task
    terrapulse_monthly_series  -> save the CSV as backend/data/monthly_series.csv
This powers the "by month" graphs. Months with no clear Landsat view have an empty NDVI/NBR cell: gaps are never filled in.
NDVI and NBR change with the seasons, so compare the same months across different years.
"""
import json, pathlib
from _points import points

JS = r"""/**
 * TerraPulse - monthly series export (generated by tools/make_monthly_series_script.py; do not edit the POINTS list by hand)
 * Landsat 8/9 Collection 2 Level-2 monthly median composites + CHIRPS monthly rainfall, at the sampled points.
 */
var POINTS = __POINTS__;
var FIRST_YEAR = 2018, LAST_YEAR = 2025;               // change these to widen or shorten the range (more months = longer export)
var BANDS = ['SR_B1', 'SR_B2', 'SR_B3', 'SR_B4', 'SR_B5', 'SR_B6', 'SR_B7'];

function maskSR(img) {
  var qa = img.select('QA_PIXEL');
  var clear = qa.bitwiseAnd(1 << 1).eq(0).and(qa.bitwiseAnd(1 << 3).eq(0)).and(qa.bitwiseAnd(1 << 4).eq(0)).and(qa.bitwiseAnd(1 << 5).eq(0));
  var sr = img.select(BANDS).multiply(0.0000275).add(-0.2);
  return sr.updateMask(clear).copyProperties(img, ['system:time_start']);
}
var pts = ee.FeatureCollection(POINTS.map(function (p) {
  return ee.Feature(ee.Geometry.Point([p.lon, p.lat]), {point_id: p.id, latitude: p.lat, longitude: p.lon});
}));
var L = ee.ImageCollection('LANDSAT/LC08/C02/T1_L2').merge(ee.ImageCollection('LANDSAT/LC09/C02/T1_L2')).filterBounds(pts.geometry().bounds());
var chirps = ee.ImageCollection('UCSB-CHG/CHIRPS/DAILY');
var empty = ee.Image.constant(ee.List.repeat(0, 7)).rename(BANDS).updateMask(ee.Image.constant(0));   // used when a month has no image at all

var months = ee.List.sequence(0, (LAST_YEAR - FIRST_YEAR + 1) * 12 - 1);
var rows = ee.FeatureCollection(months.map(function (i) {
  var a = ee.Date.fromYMD(FIRST_YEAR, 1, 1).advance(ee.Number(i), 'month'), b = a.advance(1, 'month');
  var coll = L.filterDate(a, b).map(maskSR);
  var comp = ee.Image(ee.Algorithms.If(coll.size().gt(0), coll.median(), empty));
  var idx = comp.normalizedDifference(['SR_B5', 'SR_B4']).rename('ndvi').addBands(comp.normalizedDifference(['SR_B5', 'SR_B7']).rename('nbr'));
  var rain = chirps.filterDate(a, b).sum().rename('rain_mm');
  return idx.addBands(rain).reduceRegions({collection: pts, reducer: ee.Reducer.mean(), scale: 30, tileScale: 4}).map(function (f) {
    return f.set({month: a.format('YYYY-MM')});
  });
})).flatten();

Export.table.toDrive({collection: rows, description: 'terrapulse_monthly_series', fileFormat: 'CSV',
  selectors: ['point_id', 'latitude', 'longitude', 'month', 'ndvi', 'nbr', 'rain_mm']});
Map.addLayer(pts, {color: 'yellow'}, 'sampled points');
print('Points:', pts.size(), '| months', (LAST_YEAR - FIRST_YEAR + 1) * 12);
"""

pts = [{"id": p["id"], "lat": round(p["lat"], 6), "lon": round(p["lon"], 6)} for p in points()]
dest = pathlib.Path(__file__).resolve().parent / "ee_monthly_series.js"
dest.write_text(JS.replace("__POINTS__", json.dumps(pts)), encoding="utf-8")
print(f"Wrote {dest} with {len(pts)} points. Paste it into the Earth Engine Code Editor and run the export task.")
